-- Farmccity Portfolio 1 schema.
-- Run once in a new, empty PostgreSQL database. This script does not drop existing data.

BEGIN;

CREATE TABLE buyers (
    buyer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL CHECK (btrim(full_name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    phone VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE farmers (
    farmer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_name VARCHAR(160) NOT NULL CHECK (btrim(farm_name) <> ''),
    contact_name VARCHAR(120) NOT NULL CHECK (btrim(contact_name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    phone VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(80) NOT NULL UNIQUE CHECK (btrim(category_name) <> '')
);

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    product_name VARCHAR(120) NOT NULL CHECK (btrim(product_name) <> ''),
    description TEXT,
    CONSTRAINT products_category_name_uq UNIQUE (category_id, product_name)
);

CREATE TABLE listings (
    listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES farmers(farmer_id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    available_quantity NUMERIC(12, 3) NOT NULL CHECK (available_quantity >= 0),
    unit VARCHAR(20) NOT NULL CHECK (btrim(unit) <> ''),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    listing_status VARCHAR(16) NOT NULL DEFAULT 'active'
        CHECK (listing_status IN ('active', 'paused', 'sold_out', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES buyers(buyer_id) ON DELETE RESTRICT,
    order_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    order_status VARCHAR(24) NOT NULL DEFAULT 'pending_payment'
        CHECK (order_status IN (
            'pending_payment',
            'paid',
            'partially_fulfilled',
            'fulfilled',
            'cancelled'
        )),
    currency_code CHAR(3) NOT NULL DEFAULT 'NGN' CHECK (currency_code = 'NGN'),
    delivery_address_line VARCHAR(200) NOT NULL
        CHECK (btrim(delivery_address_line) <> ''),
    delivery_city VARCHAR(100) NOT NULL CHECK (btrim(delivery_city) <> ''),
    delivery_region VARCHAR(100) NOT NULL CHECK (btrim(delivery_region) <> ''),
    delivery_country_code CHAR(2) NOT NULL
        CHECK (delivery_country_code ~ '^[A-Z]{2}$'),
    delivery_postal_code VARCHAR(20)
);

CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    listing_id BIGINT NOT NULL REFERENCES listings(listing_id) ON DELETE RESTRICT,
    quantity NUMERIC(12, 3) NOT NULL CHECK (quantity > 0),
    unit_snapshot VARCHAR(20) NOT NULL CHECK (btrim(unit_snapshot) <> ''),
    unit_price_snapshot NUMERIC(12, 2) NOT NULL CHECK (unit_price_snapshot > 0),
    CONSTRAINT order_items_order_listing_uq UNIQUE (order_id, listing_id)
);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE
        REFERENCES orders(order_id) ON DELETE RESTRICT,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    payment_status VARCHAR(12) NOT NULL DEFAULT 'pending'
        CHECK (payment_status IN ('pending', 'paid', 'failed')),
    paid_at TIMESTAMPTZ,
    CONSTRAINT payments_paid_at_ck CHECK (
        (payment_status = 'paid' AND paid_at IS NOT NULL)
        OR (payment_status <> 'paid' AND paid_at IS NULL)
    )
);

CREATE TABLE farmer_payouts (
    payout_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    farmer_id BIGINT NOT NULL REFERENCES farmers(farmer_id) ON DELETE RESTRICT,
    gross_amount NUMERIC(12, 2) NOT NULL CHECK (gross_amount > 0),
    commission_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.0100
        CHECK (commission_rate = 0.0100),
    commission_amount NUMERIC(12, 2) NOT NULL CHECK (commission_amount >= 0),
    net_amount NUMERIC(12, 2) NOT NULL CHECK (net_amount >= 0),
    payout_status VARCHAR(12) NOT NULL DEFAULT 'pending'
        CHECK (payout_status IN ('pending', 'paid', 'failed')),
    paid_at TIMESTAMPTZ,
    CONSTRAINT farmer_payouts_order_farmer_uq UNIQUE (order_id, farmer_id),
    CONSTRAINT farmer_payouts_commission_ck CHECK (
        commission_amount = ROUND(gross_amount * commission_rate, 2)
    ),
    CONSTRAINT farmer_payouts_net_amount_ck CHECK (
        net_amount = gross_amount - commission_amount
    ),
    CONSTRAINT farmer_payouts_paid_at_ck CHECK (
        (payout_status = 'paid' AND paid_at IS NOT NULL)
        OR (payout_status <> 'paid' AND paid_at IS NULL)
    )
);

CREATE TABLE deliveries (
    delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    farmer_id BIGINT NOT NULL REFERENCES farmers(farmer_id) ON DELETE RESTRICT,
    delivery_status VARCHAR(12) NOT NULL DEFAULT 'pending'
        CHECK (delivery_status IN (
            'pending',
            'preparing',
            'shipped',
            'delivered',
            'cancelled'
        )),
    tracking_reference VARCHAR(100),
    shipped_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    CONSTRAINT deliveries_order_farmer_uq UNIQUE (order_id, farmer_id),
    CONSTRAINT deliveries_shipped_at_ck CHECK (
        delivery_status NOT IN ('shipped', 'delivered')
        OR shipped_at IS NOT NULL
    ),
    CONSTRAINT deliveries_delivered_at_ck CHECK (
        delivery_status <> 'delivered' OR delivered_at IS NOT NULL
    ),
    CONSTRAINT deliveries_timestamp_order_ck CHECK (
        delivered_at IS NULL
        OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at)
    )
);

COMMIT;
